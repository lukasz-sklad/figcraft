def load_tsv(path):
    m = {}
    if not os.path.exists(path): return m
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip("\r\n")
            if not line or line.startswith("#"): continue
            parts = line.split("\t")
            if len(parts) >= 3:
                m[parts[1].strip()] = parts[2].strip()
            elif len(parts) == 2:
                m[parts[0].strip()] = parts[1].strip()
    return m

